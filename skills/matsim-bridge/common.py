"""Shared pieces of the MATSim bridge: one definition of the network, the demand and the unit conventions.

Everything here is deliberately a copy of (or an import from) what the static fidelity benchmark
(evidence/fidelity-benchmark/fidelity_benchmark.py) does, so the dynamic cross-check compares like with like:

  * same graph      : segment endpoints of docs/proposal/towns.json, largest connected component,
                      duplicate parallel edges collapsed to the faster one;
  * same speeds     : major 50 km/h, minor 30 km/h (skills/osm-network HWY_SPEEDS "secondary"/"residential");
  * same demand     : fidelity_benchmark.make_trips with numpy default_rng(2026) on the 2,500 building centroids,
                      4,000 trips generated, the first N used (so any N is a strict subset of the static OD set).
"""
import ast
import math
import sys
from pathlib import Path

import networkx as nx
import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
TOWNS_JSON = ROOT / "docs/proposal/towns.json"
BENCH_DIR = ROOT / "evidence/fidelity-benchmark"
sys.path.insert(0, str(BENCH_DIR))
import fidelity_benchmark as fb  # noqa: E402  (make_trips, kpis, engine_a, zone_ids, constants)

CRS = "EPSG:32632"          # UTM 32N metres, the frame of towns.json
SEED = 2026                 # fidelity_benchmark.py --seed default
N_TRIPS_FULL = fb.N_TRIPS   # 4000 trips generated by the static benchmark per town
TOWN_NAMES = ("molde", "kristiansund")


def _hwy_speeds():
    """Read HWY_SPEEDS from skills/osm-network without importing osmnx (parsed with ast)."""
    src = (ROOT / "skills/osm-network/scripts/osm_network.py").read_text()
    for node in ast.parse(src).body:
        if isinstance(node, ast.Assign) and any(getattr(t, "id", "") == "HWY_SPEEDS" for t in node.targets):
            return ast.literal_eval(node.value)
    raise RuntimeError("HWY_SPEEDS not found in osm_network.py")


HWY_SPEEDS = _hwy_speeds()
# towns.json keeps only a binary major flag (motorway..tertiary merged), so the class -> HWY_SPEEDS mapping is
# major -> "secondary", minor -> "residential": 50 and 30 km/h, identical to the static benchmark's V_MAJOR / V_MINOR.
V_KMH = {"major": float(HWY_SPEEDS["secondary"]), "minor": float(HWY_SPEEDS["residential"])}
assert V_KMH == {"major": fb.V_MAJOR, "minor": fb.V_MINOR}, "bridge speeds drifted from the static benchmark"

# Capacity (veh/h for the whole link) and lanes by class. ASSUMPTIONS: towns.json stores no lane or capacity data.
CAPACITY = {"major": 1500.0, "minor": 600.0}
LANES = {"major": 1, "minor": 1}


def load_town(town):
    if town not in TOWN_NAMES:
        raise SystemExit(f"unknown town {town!r}; choose from {TOWN_NAMES}")
    import json
    return json.loads(TOWNS_JSON.read_text())[town]


def build_graph(town_data):
    """Undirected graph, same construction as fidelity_benchmark.build_graph, but keeping the road class.

    Node = (x, y) of a segment endpoint; edge attributes: t (s at class speed), L (polyline length, m), cls.
    """
    G = nx.Graph()
    for maj, c, _share in town_data["roads"]:
        c = [tuple(p) for p in c]
        a, b = c[0], c[-1]
        if a == b:
            continue
        L = sum(math.dist(c[i], c[i + 1]) for i in range(len(c) - 1))
        cls = "major" if maj else "minor"
        t = L / (V_KMH[cls] / 3.6)
        if not G.has_edge(a, b) or G[a][b]["t"] > t:
            G.add_edge(a, b, t=t, L=L, cls=cls)
    return G.subgraph(max(nx.connected_components(G), key=len)).copy()


def static_trips(town_data, n_agents, seed=SEED):
    """The static benchmark's OD set: (points, o, d) for the FIRST n_agents of its 4,000 trips."""
    pts = np.array(town_data["points"], float)
    rng = np.random.default_rng(seed)
    o, d = fb.make_trips(pts, rng)          # identical call sequence to fidelity_benchmark.run_town
    return pts, o[:n_agents], d[:n_agents], o, d


def hhmmss(sec):
    sec = int(round(sec))
    return f"{sec // 3600:02d}:{sec % 3600 // 60:02d}:{sec % 60:02d}"
